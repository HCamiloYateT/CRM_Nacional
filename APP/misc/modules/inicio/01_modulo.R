# Inicio: guía comercial sin consultas ni cálculos ----
InicioCRMUI <- function(id) {
  shiny::tags$main(id = shiny::NS(id)("guia"), style = "padding:10px;max-width:1100px;line-height:1.65;",
    shiny::tags$h2("Bienvenido al CRM Nacional"),
    shiny::tags$p(paste("Consulta tus resultados, conoce tus clientes y organiza el seguimiento comercial",
      "desde un solo lugar.")),
    shiny::tags$h3("Antes de consultar"),
    shiny::tags$p(paste("Abre los filtros del panel derecho y revisa el período, asesor, línea de negocio, segmento",
      "y productos. Los filtros limitan la información a la que ya tienes acceso; no amplían tus permisos.",
      "Usa Actualizar en el encabezado para volver a leer la información disponible.")),
    shiny::tags$h3("Qué encontrarás en cada sección"),
    shiny::tags$dl(
      shiny::tags$dt("GENERALIDADES"),
      shiny::tags$dd(paste("El resumen ejecutivo muestra los indicadores calculados y permite abrir su detalle.",
        "Aquí también puedes revisar el cuadre financiero, la evolución del negocio, la composición de las ventas",
        "y los indicadores de mercado.")),
      shiny::tags$dt("GESTIÓN COMERCIAL"),
      shiny::tags$dd(paste("Compara sacos y margen con el presupuesto. Revisa oportunidades, pendientes, pedidos,",
        "notas y tareas, fidelidad y cartera. Variables (Bono) es una referencia: los parámetros provisionales",
        "no constituyen una liquidación oficial.")),
      shiny::tags$dt("PROSPECCIÓN"),
      shiny::tags$dd(paste("Sigue contactos, prospectos, leads, clientes y descartados en el Kanban o sus tablas.",
        "Consulta las gestiones y el potencial de cada entidad. Por ahora los contactos y leads de prueba son",
        "simulados. Los clientes importados se identifican como CARGA INICIAL; su ingreso reconstruido",
        "no representa una conversión comercial observada.")),
      shiny::tags$dt("COHORTES DE CLIENTES"),
      shiny::tags$dd(paste("Observa cómo cambian los grupos de clientes a lo largo del tiempo: estados, retención,",
        "ventas, margen y frecuencia. Una unidad comercial es un cliente en una línea de negocio; el mismo",
        "cliente puede participar en más de una unidad.")),
      shiny::tags$dt("HERRAMIENTAS"),
      shiny::tags$dd(paste("Utiliza las calculadoras y tablas de conversión para preparar y comparar",
        "alternativas comerciales.")),
      shiny::tags$dt("PRODUCTOS"),
      shiny::tags$dd(paste("Explora las ventas y el margen por producto. Market Basket ayuda a encontrar productos",
        "que suelen comprarse juntos. En Productos sin clasificar puedes completar las clasificaciones faltantes.")),
      shiny::tags$dt("CONSULTA INDIVIDUAL"),
      shiny::tags$dd(paste("Busca una entidad por nombre o NIT para consultar su ficha, cuentas relacionadas,",
        "gestiones, pedidos, productos, oportunidades, cartera y análisis disponibles.")),
      shiny::tags$dt("ADMINISTRAR"),
      shiny::tags$dd("Disponible para administradores: catálogos, escalas y configuración de módulos transversales.")),
    shiny::tags$h3("Qué puedes ver y modificar"),
    shiny::tags$p(paste("La información comercial se limita a las asignaciones autorizadas para tu usuario.",
      "En prospección se considera la creación o asignación del registro. En tareas puedes ver las que creaste",
      "o te asignaron. Los administradores tienen un alcance ampliado y acceso a Administración.",
      "Consultar un registro no significa que puedas editarlo: cada acción verifica sus permisos y requisitos.")),
    shiny::tags$h3("Cómo interpretar los resultados"),
    shiny::tags$p(paste("Revisa siempre el período y la fecha de actualización de cada vista. Los meses cerrados",
      "usan la información financiera; las facturas sin cierre y los pedidos estimados se distinguen y pueden",
      "variar. Un pedido estimado no es una venta confirmada. Un guion indica que el indicador no está disponible;",
      "cero significa que se calculó y no hubo cantidad. Las vistas en construcción aún no ofrecen resultados.")),
    shiny::tags$p(paste("En el encabezado tienes el glosario para consultar los términos",
      "y las escalas para entender los colores.")))
}

