GlosarioCRMUI <- function() {
  shiny::tags$div(class = "dropdown",
    shiny::tagAppendAttributes(racafeForms::racafeButton("glosario_crm", NULL, icon = "book-open",
      title = "Glosario comercial", variant = "secondary", size = "xs"),
      `data-toggle` = "dropdown", `aria-haspopup` = "true", `aria-expanded` = "false"),
    shiny::tags$div(class = "dropdown-menu kb-scale-menu", `aria-labelledby` = "glosario_crm",
      style = paste("width:420px;min-width:0;max-width:calc(100vw - 24px);max-height:70vh;",
        "overflow-y:auto;padding:16px;"),
      shiny::tags$h5("Glosario comercial"),
      shiny::tags$dl(lapply(names(.INICIO_GLOSARIO), function(termino) shiny::tagList(
        shiny::tags$dt(termino), shiny::tags$dd(style = "margin-bottom:10px;", .INICIO_GLOSARIO[[termino]]))))))
}
