const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.setDefaultTimeout(20000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3902');
 await page.locator('#consulta-ficha-tabla .gt_table').waitFor();
 await page.evaluate(()=>$('#consulta-entidad').selectpicker('val','nit:102').trigger('change'));
 await page.waitForFunction(()=>document.querySelector('#consulta-identidad').innerText.includes('SEDE NORTE'));
 const directorio=page.locator('details').filter({has:page.locator('summary',{hasText:'Directorio empresarial'})}).first();
 await directorio.locator('summary').click();
 await page.waitForFunction(()=>document.querySelector('#consulta-directorio_conteo').innerText.includes('registros'));
 assert.match(await directorio.locator('summary').innerText(),/registros/);
 await page.locator('#consulta-contenido a[data-value="Gestión y seguimiento"]').click();
 const recorrido=page.locator('details').filter({has:page.locator('summary',{hasText:'Recorrido comercial completo'})}).first();
 await recorrido.locator('summary').click();
 await page.locator('#consulta-cronologia-tabla .gt_table').waitFor();
 assert.match(await recorrido.innerText(),/Conversión|CLIENTE|LEAD/);
 await page.locator('#consulta-contenido a[data-value="Ejecución y productos"]').click();
 await page.locator('#consulta-productos-tabla .gt_table').waitFor();
 assert.match(await page.locator('#consulta-productos-tabla').innerText(),/Marca sede|Referencia sede/);
 assert.doesNotMatch(await page.locator('#consulta-productos-tabla').innerText(),/Categoría/);
 await page.locator('summary',{hasText:'Pedidos, precios históricos'}).click();
 await page.locator('#consulta-pedidos_precios-tabla .gt_table').waitFor();
 await page.waitForFunction(()=>document.querySelector('#consulta-rango_precios').innerText.includes('12,000'));
 await page.evaluate(()=>Shiny.setInputValue('consulta-precio_comparar',12001,{priority:'event'}));
 await page.locator('#consulta-precio_cercano-tabla .gt_table').waitFor();
 assert.match(await page.locator('#consulta-precio_cercano-tabla').innerText(),/12,000/);
 assert.match(await page.locator('#consulta-fecha_mercado').innerText(),/Referencia: pedido/);
 await page.locator('a[data-value="Basket"]').click();
 assert.match(await page.locator('body').innerText(),/Qué es Market Basket/);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/perfil-precios-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('OK: secciones con conteos, referencias comerciales, precios históricos, comparación y Basket.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
